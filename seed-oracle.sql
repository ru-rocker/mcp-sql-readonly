ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE TABLE app.customers (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR2(100) NOT NULL,
  email      VARCHAR2(200) UNIQUE NOT NULL,
  city       VARCHAR2(100),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE app.products (
  id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name     VARCHAR2(100) NOT NULL,
  category VARCHAR2(50) NOT NULL,
  price    NUMBER(12,2) NOT NULL CHECK (price >= 0),
  stock    NUMBER DEFAULT 0 NOT NULL
);

CREATE TABLE app.orders (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER NOT NULL REFERENCES app.customers(id),
  status      VARCHAR2(20) NOT NULL CHECK (status IN ('pending','paid','shipped','cancelled')),
  ordered_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE app.order_items (
  order_id   NUMBER NOT NULL REFERENCES app.orders(id),
  product_id NUMBER NOT NULL REFERENCES app.products(id),
  qty        NUMBER NOT NULL CHECK (qty > 0),
  unit_price NUMBER(12,2) NOT NULL,
  PRIMARY KEY (order_id, product_id)
);

